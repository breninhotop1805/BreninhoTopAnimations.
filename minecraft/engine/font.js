export function measure(text) { let w = 0; for (const ch of text) { const g = G[ch] || G[' ']; w += g[0].length + 1; } return w - 1; }
// desenha com sombra (deslocada 1px, cor 25%) como no jogo
export function drawText(g, text, x, y, s, color = '#fff', shadow = true, shadowColor = '#3f3f3f') {
  const pass = (ox, oy, col) => {
    let cx = x; g.fillStyle = col;
    for (const ch of text) { const gl = G[ch] || G[' ']; gl.forEach((row, j) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') g.fillRect(cx + (i + ox) * s, y + (j + oy) * s, s, s); }); cx += (gl[0].length + 1) * s; }
  };
  if (shadow) pass(1, 1, shadowColor); pass(0, 0, color);
}
drawText.measure = measure;
