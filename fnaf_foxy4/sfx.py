def chip_sweep(f0, f1, d=0.25):
    t = np.arange(int(d * SR)) / SR; f = f0 + (f1 - f0) * t / d; return np.sign(np.sin(2 * np.pi * np.cumsum(f) / SR)) * np.exp(-t / (d * 0.7))
